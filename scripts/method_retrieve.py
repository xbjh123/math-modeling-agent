def _match_keywords(text: str, keywords: list) -> int:
    """计算命中的关键词数量（简单包含匹配）。"""
    text_l = text.lower()
    hits = 0
    for kw in keywords:
        if kw.lower() in text_l:
            hits += 1
    return hits


def retrieve_methods(problem_desc, top_k=4, library_path=None):
    """检索相关建模方法，返回 [(方法, 核心思想, 归属流派, 命中数)]，按命中数降序。

    Args:
        problem_desc: 题目/子任务描述字符串。
        top_k: 返回前多少个方法。
        library_path: HMML 库文件路径（本版用内置索引，忽略；预留 embedding 版）。
    """
    scored = []
    for method, (keywords, idea, school) in METHOD_INDEX.items():
        hits = _match_keywords(problem_desc, keywords)
        if hits > 0:
            scored.append((method, idea, school, hits))
    # 按命中数降序；同分按方法名排序保证可复现
    scored.sort(key=lambda x: (-x[3], x[0]))
    return scored[:top_k]


def save_to_json(results, output_dir):
    """把检索结果落盘为 .modeling/specs/00_retrieval.json，供 subagent 消费。

    Args:
        results: retrieve_methods() 的返回值 [(method, idea, school, hits), ...]。
        output_dir: 工作区根目录（.modeling 的上级）。
    """
    if results is None:
        results = []
    payload = {
        "retrieved_methods": [
            {"method": m, "core_idea": idea, "school": school, "hits": hits}
            for (m, idea, school, hits) in results
        ],
        "note": "这些是 HMML 检索命中的候选方法；主线程据 school 分配到对应 subagent 发散。",
    }
    specs_dir = Path(output_dir) / ".modeling" / "specs"
    specs_dir.mkdir(parents=True, exist_ok=True)
    out = specs_dir / "00_retrieval.json"
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return str(out)


